import { promises as fsp } from 'node:fs';
import path from 'node:path';
import { hashContentPayload, type ContentHashInput } from '../../scripts/content-hash';
import type {
  ClassifiedRow,
  ExtractEnvelope,
  ExtractRow,
  Locale,
  TargetType,
} from '../../scripts/extract-modx.types';
import { normalizeCanonicalPath } from './canonical-path';

export const EXPECTED_EXTRACT_JSON_VERSION = 1;
export const EXTRACT_JSON_PATH = path.resolve(__dirname, '..', '..', '..', '..', 'plans', 'modx-extract.json');

export const TARGET_UID_BY_TYPE: Record<TargetType, string> = {
  page: 'api::page.page',
  disease: 'api::disease.disease',
  'disease-category': 'api::disease-category.disease-category',
  service: 'api::service.service',
  'service-category': 'api::service-category.service-category',
};

export type MigrationAnnotation = {
  reason_code: string;
  detail?: string;
};

export type RouteLookups = {
  by_modx_id: Map<number, ClassifiedRow>;
  by_path: Map<string, ClassifiedRow>;
  canonical_keys: Set<string>;
};

export type BodyRewriteContext = {
  locale: Locale;
  lookups: RouteLookups;
  asset_paths: Set<string>;
};

export type BodyRewriteResult = {
  html: string;
  annotations: MigrationAnnotation[];
};

export type DesiredContentPayload = {
  uid: string;
  content_hash: string;
  data: Record<string, unknown>;
  annotations: MigrationAnnotation[];
};

export type DesiredUrlMapping = {
  path: string;
  type: 'canonical';
  isAutoGenerated: false;
  legacyPaths: string[];
};

export async function loadExtractEnvelope(extractPath: string = EXTRACT_JSON_PATH): Promise<ExtractEnvelope> {
  const parsed = JSON.parse(await fsp.readFile(extractPath, 'utf8')) as ExtractEnvelope;
  if (parsed.schema_version !== EXPECTED_EXTRACT_JSON_VERSION) {
    throw new Error('extract_json_schema_version_mismatch');
  }
  return parsed;
}

export function isClassifiedRow(row: ExtractRow): row is ClassifiedRow {
  return 'target_type' in row;
}

export function normalizeLegacyPath(input: string): string {
  let value = input.trim();
  value = value.replace(/^https?:\/\/(?:www\.)?myorl\.gr\/?/i, '');
  value = value.replace(/^\/+/, '');

  if (value === 'el' || value === 'ru') {
    return '';
  }
  if (value.startsWith('el/')) {
    value = value.slice(3);
  } else if (value.startsWith('ru/')) {
    value = value.slice(3);
  }

  return normalizeCanonicalPath(value);
}

export function routePathFor(locale: Locale, canonicalPath: string): string {
  return canonicalPath ? `/${locale}/${canonicalPath}` : `/${locale}`;
}

function lookupKey(locale: Locale, canonicalPath: string): string {
  return `${locale}:${canonicalPath}`;
}

export function buildRouteLookups(rows: readonly ExtractRow[]): RouteLookups {
  const byModxId = new Map<number, ClassifiedRow>();
  const byPath = new Map<string, ClassifiedRow>();
  const canonicalKeys = new Set<string>();

  for (const row of rows) {
    if (!isClassifiedRow(row)) continue;
    byModxId.set(row.modx_id, row);

    const canonicalKey = lookupKey(row.locale, row.canonical_path);
    canonicalKeys.add(canonicalKey);
    byPath.set(canonicalKey, row);

    for (const legacyPath of row.legacy_paths) {
      byPath.set(lookupKey(row.locale, normalizeLegacyPath(legacyPath)), row);
    }
  }

  return {
    by_modx_id: byModxId,
    by_path: byPath,
    canonical_keys: canonicalKeys,
  };
}

export function buildAssetPathSet(envelope: ExtractEnvelope): Set<string> {
  return new Set(envelope.asset_inventory.map((entry) => entry.path));
}

type ResolvedPath = { locale: Locale; canonicalPath: string };

function parseInternalPath(rawHref: string, currentLocale: Locale): ResolvedPath | null {
  let value = rawHref.trim();
  value = value.replace(/^https?:\/\/(?:www\.)?myorl\.gr/i, '');
  if (!value.startsWith('/')) {
    return null;
  }

  value = value.replace(/^\/+/, '');
  let locale = currentLocale;
  if (value === 'el' || value.startsWith('el/')) {
    locale = 'el';
    value = value.slice(2).replace(/^\/+/, '');
  } else if (value === 'ru' || value.startsWith('ru/')) {
    locale = 'ru';
    value = value.slice(2).replace(/^\/+/, '');
  }

  return {
    locale,
    canonicalPath: normalizeCanonicalPath(value),
  };
}

function maybeAssetPath(rawHref: string): string | null {
  let value = rawHref.trim();
  value = value.replace(/^https?:\/\/(?:www\.)?myorl\.gr\/?/i, '');
  value = value.replace(/^\/+/, '');
  if (
    value.startsWith('assets/') ||
    value.startsWith('files/') ||
    value.startsWith('uploads/') ||
    value.startsWith('webp/') ||
    value.startsWith('template/') ||
    value.startsWith('ru/assets/') ||
    value.startsWith('ru/files/') ||
    value.startsWith('ru/template/') ||
    value.startsWith('ru/webp/')
  ) {
    return value;
  }
  return null;
}

function replaceAnchorHrefs(html: string, context: BodyRewriteContext): BodyRewriteResult {
  const annotations: MigrationAnnotation[] = [];
  const next = html.replace(
    /(<a\b[^>]*?\bhref=)(['"])(.*?)(\2)([^>]*>)/gi,
    (match, prefix, quote, href, suffixQuote, tail) => {
      const assetPath = maybeAssetPath(href);
      if (assetPath) {
        if (!context.asset_paths.has(assetPath)) {
          annotations.push({ reason_code: 'missing_asset', detail: assetPath });
          return `${prefix}${quote}/${assetPath}${suffixQuote} data-migration-missing-asset="true"${tail}`;
        }
        return `${prefix}${quote}/${assetPath}${suffixQuote}${tail}`;
      }

      const parsed = parseInternalPath(href, context.locale);
      if (!parsed) {
        return match;
      }

      const target = context.lookups.by_path.get(lookupKey(parsed.locale, parsed.canonicalPath));
      if (!target) {
        annotations.push({ reason_code: 'unresolved_legacy_url', detail: href });
        return `${prefix}${quote}${href}${suffixQuote} data-migration-unresolved="true"${tail}`;
      }

      return `${prefix}${quote}${routePathFor(target.locale, target.canonical_path)}${suffixQuote}${tail}`;
    },
  );

  return { html: next, annotations };
}

function replaceImgSrcs(html: string, context: BodyRewriteContext): BodyRewriteResult {
  const annotations: MigrationAnnotation[] = [];
  const next = html.replace(
    /(<img\b[^>]*?\bsrc=)(['"])(.*?)(\2)([^>]*>)/gi,
    (match, prefix, quote, src, suffixQuote, tail) => {
      const assetPath = maybeAssetPath(src);
      if (!assetPath) {
        return match;
      }

      if (!context.asset_paths.has(assetPath)) {
        annotations.push({ reason_code: 'missing_asset', detail: assetPath });
        return `${prefix}${quote}/${assetPath}${suffixQuote} data-migration-missing-asset="true"${tail}`;
      }

      return `${prefix}${quote}/${assetPath}${suffixQuote}${tail}`;
    },
  );

  return { html: next, annotations };
}

function replaceShortcodes(html: string, context: BodyRewriteContext): BodyRewriteResult {
  const annotations: MigrationAnnotation[] = [];

  const resolvedLinks = html.replace(/\[\[~(\d+)\]\]/g, (token, rawId) => {
    const modxId = Number(rawId);
    const target = context.lookups.by_modx_id.get(modxId);
    if (!target) {
      annotations.push({ reason_code: 'unresolved_modx_shortcode', detail: token });
      return `<!-- MODX:unresolved:${token} -->`;
    }

    return routePathFor(target.locale, target.canonical_path);
  });

  const replaced = resolvedLinks.replace(/\[\[[^[\]]+\]\]/g, (token) => {
    annotations.push({ reason_code: 'unresolved_modx_shortcode', detail: token });
    return `<!-- MODX:unresolved:${token} -->`;
  });

  return { html: replaced, annotations };
}

export function rewriteBodyHtml(bodyHtml: string, context: BodyRewriteContext): BodyRewriteResult {
  const shortcodeResult = replaceShortcodes(bodyHtml, context);
  const anchorResult = replaceAnchorHrefs(shortcodeResult.html, context);
  const imageResult = replaceImgSrcs(anchorResult.html, context);

  return {
    html: imageResult.html,
    annotations: [
      ...shortcodeResult.annotations,
      ...anchorResult.annotations,
      ...imageResult.annotations,
    ],
  };
}

export function normalizeLegacyPaths(paths: readonly string[]): string[] {
  return [...new Set(paths.map((pathValue) => normalizeLegacyPath(pathValue)).filter(Boolean))].sort();
}

export function buildDesiredContentPayload(
  row: ClassifiedRow,
  context: BodyRewriteContext,
): DesiredContentPayload {
  const rewritten = rewriteBodyHtml(row.body_html, context);
  const needsReviewAnnotations = [...rewritten.annotations];

  const seo =
    row.seo_meta_title || row.seo_meta_description
      ? {
          metaTitle: row.seo_meta_title || row.title,
          metaDescription: row.seo_meta_description ?? '',
        }
      : null;

  const hashInput: ContentHashInput = {
    title: row.title,
    body: rewritten.html,
    canonicalPath: row.canonical_path,
    seo,
    parent_modx_id: row.parent_modx_id ?? null,
    category_modx_id: row.category_modx_id ?? null,
  };

  const data: Record<string, unknown> = {
    title: row.title,
    canonicalPath: row.canonical_path,
    modxId: row.modx_id,
    _migrationContentHash: hashContentPayload(hashInput),
    needs_review: row.needs_review_seed || needsReviewAnnotations.length > 0,
    seo,
  };

  if (row.target_type === 'page' || row.target_type === 'disease' || row.target_type === 'service') {
    data.body = rewritten.html;
  } else {
    data.description = rewritten.html;
  }

  return {
    uid: TARGET_UID_BY_TYPE[row.target_type],
    content_hash: data._migrationContentHash as string,
    data,
    annotations: needsReviewAnnotations,
  };
}

export function buildDesiredUrlMapping(
  row: ClassifiedRow,
  lookups: RouteLookups,
  existingLegacyOwners: Map<string, number>,
): { desired: DesiredUrlMapping; annotations: MigrationAnnotation[] } {
  const annotations: MigrationAnnotation[] = [];
  const filteredLegacyPaths: string[] = [];

  for (const legacyPath of normalizeLegacyPaths(row.legacy_paths)) {
    const key = lookupKey(row.locale, legacyPath);
    const canonicalOwner = lookups.by_path.get(key);
    if (canonicalOwner && canonicalOwner.modx_id !== row.modx_id) {
      annotations.push({
        reason_code: 'legacy_path_collides_with_canonical',
        detail: legacyPath,
      });
      continue;
    }

    const owner = existingLegacyOwners.get(key);
    if (owner !== undefined && owner !== row.modx_id) {
      annotations.push({
        reason_code: 'legacy_path_ambiguous',
        detail: legacyPath,
      });
      continue;
    }

    existingLegacyOwners.set(key, row.modx_id);
    filteredLegacyPaths.push(legacyPath);
  }

  return {
    desired: {
      path: row.canonical_path,
      type: 'canonical',
      isAutoGenerated: false,
      legacyPaths: filteredLegacyPaths,
    },
    annotations,
  };
}

import type { Core } from '@strapi/strapi';

const URL_MAPPING_UID = 'api::url-mapping.url-mapping';

/** Locales we expect for myorl. Extend when adding locales in Strapi admin. */
const ROUTING_LOCALES = ['el', 'ru'] as const;

/** Map routable UIDs to their relation field names in the UrlMapping content type. */
const UID_TO_RELATION: Record<string, string> = {
  'api::page.page': 'page',
  'api::disease.disease': 'disease',
  'api::disease-category.disease-category': 'disease_category',
  'api::service.service': 'service',
  'api::service-category.service-category': 'service_category',
};

type RoutableEntry = {
  documentId: string;
  locale?: string;
  canonicalPath?: string;
  publishedAt?: string | null;
};

function getLocalesFromPublishResult(result: unknown): RoutableEntry[] {
  if (!result || typeof result !== 'object') return [];
  const entries = (result as { entries?: RoutableEntry[] }).entries;
  return Array.isArray(entries) ? entries : [];
}

async function deleteUrlMappings(
  strapi: Core.Strapi,
  uid: string,
  documentId: string,
  locale?: string | null
) {
  const relationField = UID_TO_RELATION[uid];
  if (!relationField) return;

  const baseFilters = {
    [relationField]: { documentId: { $eq: documentId } },
    type: { $eq: 'canonical' },
  };

  const locales = locale && locale !== '*' ? [locale] : [...ROUTING_LOCALES];

  for (const loc of locales) {
    const found = await strapi.documents(URL_MAPPING_UID).findMany({
      filters: baseFilters as any,
      locale: loc,
    });
    for (const doc of found) {
      await strapi.documents(URL_MAPPING_UID).delete({
        documentId: doc.documentId,
        locale: doc.locale ?? loc,
      });
    }
  }
}

async function upsertUrlMapping(strapi: Core.Strapi, uid: string, entry: RoutableEntry) {
  const relationField = UID_TO_RELATION[uid];
  if (
    !relationField ||
    !entry.documentId ||
    !entry.locale ||
    typeof entry.canonicalPath !== 'string' ||
    !entry.publishedAt
  ) {
    return;
  }

  // 1. Find the current canonical mapping for this document in this locale
  const existingCanonical = await strapi.documents(URL_MAPPING_UID).findFirst({
    filters: {
      [relationField]: { documentId: { $eq: entry.documentId } },
      type: { $eq: 'canonical' },
    } as any,
    locale: entry.locale,
  });

  // 2. If the path has changed, convert the old one to a 301 (Slug Drift)
  if (existingCanonical && existingCanonical.path !== entry.canonicalPath) {
    await strapi.documents(URL_MAPPING_UID).update({
      documentId: existingCanonical.documentId,
      locale: entry.locale,
      data: {
        type: 'redirect_301',
        isAutoGenerated: true,
      },
    });
  }

  // 3. Check if the NEW path is already taken in this locale
  const collision = await strapi.documents(URL_MAPPING_UID).findFirst({
    filters: {
      path: { $eq: entry.canonicalPath },
    } as any,
    locale: entry.locale,
  });

  if (collision) {
    // If it belongs to a different document, we have a problem (SEO collision)
    const targetDocId = (collision as any)[relationField]?.documentId;
    if (targetDocId && targetDocId !== entry.documentId) {
      strapi.log.warn(
        `SEO Collision: Path "${entry.canonicalPath}" in locale "${entry.locale}" is already mapped to ${targetDocId}. Skipping upsert.`
      );
      return;
    }

    await strapi.documents(URL_MAPPING_UID).update({
      documentId: (collision as any).documentId,
      locale: entry.locale,
      data: {
        type: 'canonical',
        isAutoGenerated: false,
        [relationField]: entry.documentId,
      },
    });
  } else {
    // 4. Create a fresh canonical mapping
    await strapi.documents(URL_MAPPING_UID).create({
      locale: entry.locale,
      data: {
        path: entry.canonicalPath,
        type: 'canonical',
        isAutoGenerated: false,
        [relationField]: entry.documentId,
      },
    });
  }
}

export async function afterDocumentAction(
  strapi: Core.Strapi,
  context: { action: string; uid: string; params: Record<string, unknown> },
  result: unknown
) {
  // Q1 middleware coexistence: the Phase 6.5 merge importer is the sole
  // UrlMapping writer for the duration of a merge run. The CLI sets
  // MIGRATION_IN_PROGRESS=true on entry and clears it on exit (success or fail).
  if (process.env.MIGRATION_IN_PROGRESS === 'true') {
    return;
  }

  const { action, uid, params } = context;
  if (!UID_TO_RELATION[uid]) {
    return;
  }

  const documentId = (params.documentId as string | undefined) || (result as RoutableEntry | null)?.documentId;
  if (!documentId) {
    return;
  }

  if (action === 'delete' || action === 'unpublish') {
    const locale = params.locale as string | undefined;
    await deleteUrlMappings(strapi, uid, documentId, locale ?? '*');
    return;
  }

  if (action === 'publish') {
    const entries = getLocalesFromPublishResult(result);
    for (const entry of entries) {
      if (entry.publishedAt && entry.locale) {
        await upsertUrlMapping(strapi, uid, entry);
      }
    }
    return;
  }

  if (action === 'create' || action === 'update') {
    const locale =
      (params.locale as string | undefined) ?? (result as RoutableEntry | null)?.locale;
    if (!locale) {
      return;
    }

    const published = await strapi.documents(uid as any).findOne({
      documentId,
      locale,
      status: 'published',
    });

    if (published?.publishedAt && (published as any).locale) {
      await upsertUrlMapping(strapi, uid, published as unknown as RoutableEntry);
    } else {
      await deleteUrlMappings(strapi, uid, documentId, locale);
    }
  }
}

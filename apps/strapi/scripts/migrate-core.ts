export type DocumentSnapshot = {
  uid: string;
  documentId: string;
  locale: 'el' | 'ru';
  canonicalPath: string;
  modxId: number | null;
  _migrationContentHash: string | null;
  needs_review: boolean;
  publishedAt: string | null;
  parentDocumentId: string | null;
  categoryDocumentId: string | null;
};

export type UrlMappingSnapshot = {
  documentId: string;
  locale: 'el' | 'ru';
  path: string;
  type: 'canonical' | 'redirect_301' | 'gone_410';
  isAutoGenerated: boolean;
  legacyPaths: string[];
  relationField: string | null;
  relationDocumentId: string | null;
};

export type CanonicalUsageIndex = {
  byCanonical: Map<string, DocumentSnapshot[]>;
  byModx: Map<string, DocumentSnapshot>;
  byUidAndDocument: Map<string, DocumentSnapshot>;
};

export function buildCanonicalUsageIndex(contentSnapshots: Map<string, DocumentSnapshot>): CanonicalUsageIndex {
  const byCanonical = new Map<string, DocumentSnapshot[]>();
  const byModx = new Map<string, DocumentSnapshot>();
  const byUidAndDocument = new Map<string, DocumentSnapshot>();

  for (const snapshot of contentSnapshots.values()) {
    const canonicalKey = `${snapshot.uid}:${snapshot.locale}:${snapshot.canonicalPath}`;
    const current = byCanonical.get(canonicalKey) ?? [];
    current.push(snapshot);
    byCanonical.set(canonicalKey, current);

    if (snapshot.modxId !== null) {
      byModx.set(`${snapshot.uid}:${snapshot.locale}:${snapshot.modxId}`, snapshot);
    }
    byUidAndDocument.set(`${snapshot.uid}:${snapshot.documentId}:${snapshot.locale}`, snapshot);
  }

  return { byCanonical, byModx, byUidAndDocument };
}

export function sortRowsForPass(rows: RouteLookups['by_modx_id'], targetTypes: string[]): ClassifiedRow[] {
  return [...rows.values()]
    .filter((row) => targetTypes.includes(row.target_type))
    .sort((a, b) => a.modx_id - b.modx_id);
}

export function sortPagesByDepth(rows: RouteLookups['by_modx_id']): ClassifiedRow[] {
  const pages = [...rows.values()].filter((row) => row.target_type === 'page');
  const depthCache = new Map<number, number>();
  const getDepth = (row: (typeof pages)[number], stack = new Set<number>()): number => {
    if (depthCache.has(row.modx_id)) return depthCache.get(row.modx_id)!;
    if (row.parent_modx_id == null) return 0;
    if (stack.has(row.modx_id)) return 1000;
    const parent = rows.get(row.parent_modx_id);
    if (!parent || parent.target_type !== 'page') return 1;
    stack.add(row.modx_id);
    const depth = getDepth(parent, stack) + 1;
    stack.delete(row.modx_id);
    depthCache.set(row.modx_id, depth);
    return depth;
  };

  return pages.sort((a, b) => {
    const depthDelta = getDepth(a) - getDepth(b);
    return depthDelta !== 0 ? depthDelta : a.modx_id - b.modx_id;
  });
}

export type ResolveExistingResult =
  | { ok: true; existing: DocumentSnapshot | null }
  | { ok: false; code: 'ambiguous_backfill_match'; detail: string }
  | { ok: false; code: 'canonical_path_collision'; detail: string };

/**
 * Backfill pass 0 + collision guard: resolve which Strapi document (if any) receives the merge.
 */
export function resolveExistingDocumentForMerge(args: {
  uid: string;
  locale: 'el' | 'ru';
  modxId: number;
  canonicalPath: string;
  indexes: CanonicalUsageIndex;
}): ResolveExistingResult {
  const { uid, locale, modxId, canonicalPath, indexes } = args;
  const canonicalKey = `${uid}:${locale}:${canonicalPath}`;
  const canonicalCandidates = indexes.byCanonical.get(canonicalKey) ?? [];
  let existing = indexes.byModx.get(`${uid}:${locale}:${modxId}`) ?? null;

  if (!existing && canonicalCandidates.length > 1) {
    return { ok: false, code: 'ambiguous_backfill_match', detail: `${canonicalCandidates.length} candidates` };
  }

  if (!existing && canonicalCandidates.length === 1) {
    existing = canonicalCandidates[0];
  }

  const collisionOwner = canonicalCandidates.find(
    (candidate) => !existing || candidate.documentId !== existing.documentId,
  );
  if (collisionOwner && !existing) {
    return { ok: false, code: 'canonical_path_collision', detail: collisionOwner.documentId };
  }

  return { ok: true, existing };
}

export type ContentMergeAction = 'create' | 'update' | 'no_change';

/**
 * Hash-gated create / update / no-op (AC-merge-2).
 */
export function selectContentMergeAction(args: {
  existing: DocumentSnapshot | null;
  desiredContentHash: string | null;
  desiredPublished: boolean;
  desiredNeedsReview: boolean;
  relationBlocked: boolean;
}): ContentMergeAction {
  const { existing, desiredContentHash, desiredPublished, desiredNeedsReview, relationBlocked } = args;
  const statusMatches = Boolean(existing?.publishedAt) === desiredPublished;
  const needsReviewUpdate = desiredNeedsReview && !existing?.needs_review;
  const hashMatches =
    !relationBlocked &&
    existing?._migrationContentHash != null &&
    existing._migrationContentHash === desiredContentHash;

  if (!existing) {
    return 'create';
  }
  if (hashMatches && !needsReviewUpdate && statusMatches) {
    return 'no_change';
  }
  return 'update';
}

/**
 * Set-only-on-true: never send `needs_review: false` on update — omit field so editor-cleared false survives (AC-merge-6).
 */
export function applyNeedsReviewSetOnlyOnTrue(
  data: Record<string, unknown>,
  desiredNeedsReview: boolean,
  hasExisting: boolean,
): void {
  if (!desiredNeedsReview && hasExisting) {
    delete data.needs_review;
  }
}

export type UrlMappingMergeAction = 'create' | 'update' | 'no_change';

/**
 * Equality-gated UrlMapping writes; legacyPaths compared sorted (AC-merge-5).
 */
export function selectUrlMappingMergeAction(
  existing: UrlMappingSnapshot | null,
  desired: {
    path: string;
    type: 'canonical' | 'redirect_301' | 'gone_410';
    isAutoGenerated: boolean;
    legacyPaths: string[];
  },
): UrlMappingMergeAction {
  const desiredLegacySorted = [...desired.legacyPaths].sort();
  if (!existing) {
    return 'create';
  }
  const existingLegacySorted = [...existing.legacyPaths].sort();
  const equal =
    existing.path === desired.path &&
    existing.type === desired.type &&
    existing.isAutoGenerated === desired.isAutoGenerated &&
    JSON.stringify(existingLegacySorted) === JSON.stringify(desiredLegacySorted);
  return equal ? 'no_change' : 'update';
}

export type ReconcileWritingOutcome = {
  nextState: 'succeeded' | 'failed';
  reasonCode: 'reconciled_after_crash' | 'crashed_before_write';
};

/**
 * Crash recovery: prior run left row in `writing` (AC-merge-14).
 */
export function reconcileWritingRowDecision(args: {
  existingDoc: { _migrationContentHash: string | null } | null;
  ledgerContentHash: string | null;
}): ReconcileWritingOutcome {
  const { existingDoc, ledgerContentHash } = args;
  const ok =
    existingDoc != null &&
    existingDoc._migrationContentHash != null &&
    existingDoc._migrationContentHash === ledgerContentHash;
  if (ok) {
    return { nextState: 'succeeded', reasonCode: 'reconciled_after_crash' };
  }
  return { nextState: 'failed', reasonCode: 'crashed_before_write' };
}
